import { Ledger } from "../models/Ledger.model.js";

export const ledgerRepository = {
  create: (data, session = null) =>
    session ? Ledger.create([data], { session }).then((r) => r[0]) : Ledger.create(data),

  findByParty: (partyId, { startDate, endDate } = {}, session = null) => {
    const query = { party: partyId, isDeleted: false };
    if (startDate || endDate) {
      query.date = {};
      if (startDate) query.date.$gte = new Date(startDate);
      if (endDate) query.date.$lte = new Date(endDate);
    }
    return Ledger.find(query).sort({ date: 1, createdAt: 1 }).session(session);
  },

  lastEntry: (partyId) =>
    Ledger.findOne({ party: partyId, isDeleted: false }).sort({ date: -1, createdAt: -1 }),

  findById: (id) => Ledger.findById(id),

  // All live entries generated by a given source document (e.g. a bilty), used
  // to reverse a bill's debit + delivery-charge credit together.
  findByRef: (refId) => Ledger.find({ refId, isDeleted: false }),

  softDelete: (id, reason, session = null) =>
    Ledger.findByIdAndUpdate(id, { isDeleted: true, editReason: reason }, { new: true, session }),

  update: (id, data, session = null) =>
    Ledger.findByIdAndUpdate(id, data, { new: true, session }),
};